-- 1. Create Database and Tables (DEPOSIT, BRANCH, CUSTOMERS, BORROW)
CREATE DATABASE dbms_lab;
USE dbms_lab;

CREATE TABLE DEPOSIT (
    ACTNO VARCHAR(5),
    CNAME VARCHAR(18),
    BNAME VARCHAR(18),
    AMOUNT DECIMAL(8,2),
    ADATE DATE
);

CREATE TABLE BRANCH (
    BNAME VARCHAR(18),
    CITY VARCHAR(18)
);

CREATE TABLE CUSTOMERS (
    CNAME VARCHAR(19),
    CITY VARCHAR(18)
);

CREATE TABLE BORROW (
    LOANNO VARCHAR(5),
    CNAME VARCHAR(18),
    BNAME VARCHAR(18),
    AMOUNT DECIMAL(8,2)
);

